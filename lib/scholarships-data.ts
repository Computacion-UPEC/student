import type { Stage } from "@/lib/student-stages"

export type ProgramKind = "Beca" | "Internship"

/**
 * Ciclo de convocatoria: en qué meses se suele poder postular (1 = enero).
 * "anual": una convocatoria por año. "varias": varias ventanas al año. "recurrente": se repite pero no todos los años.
 * approx: los meses salen de ciclos anteriores o fuentes no oficiales; confirmar cada año.
 */
export type Cycle = {
  frequency: "anual" | "varias" | "recurrente"
  months: number[]
  approx?: boolean
}

export type Program = {
  id: string
  kind: ProgramKind
  name: string
  provider: string
  place: string
  level: string
  funding: string
  eligibility: string
  timing: string
  url: string
  /** Advertencia visible en la tarjeta (requisitos poco comunes, disponibilidad incierta). */
  warning?: string
  /** Sin ciclo: la fecha depende de cada programa o no se publica. */
  cycle?: Cycle
  /** Fecha de apertura (ISO) de la convocatoria actual; antes de ella la tarjeta dice cuándo abre. */
  opensAt?: string
  /** Fecha de cierre (ISO) de la convocatoria actual; entre la apertura y el cierre la tarjeta se marca como abierta. */
  closesAt?: string
  /** El programa es específico de TI o incluye campos de TI; el texto explica cuáles. */
  itFocus?: string
  /** Etapas de la carrera en las que se puede postular. */
  stages: Stage[]
  tags: string[]
}

